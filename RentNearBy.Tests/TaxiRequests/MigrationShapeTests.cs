using System.Reflection;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using RentNearBy.Infrastructure.Data;

namespace RentNearBy.Tests.TaxiRequests;

// Model and migration metadata only, no connection.
public class MigrationShapeTests
{
    private static readonly string[] NewTables =
    [
        "TaxiRequests", "TaxiRequestOffers", "TaxiBookings", "TaxiRatings",
        "DriverDispatchStates", "TaxiDispatchCities", "DueActions",
    ];

    private static readonly (string Table, string Index)[] NewIndexes =
    [
        ("TaxiRequests", "ux_taxirequests_active_trip"),
        ("TaxiRequests", "ux_taxirequests_client"),
        ("TaxiRequests", "ix_taxirequests_dispatch"),
        ("TaxiRequests", "ix_taxirequests_traveller"),
        ("TaxiRequests", "ix_taxirequests_closed"),
        ("TaxiRequestOffers", "ux_taxioffers_request_driver"),
        ("TaxiRequestOffers", "ux_taxioffers_driver_ringing"),
        ("TaxiRequestOffers", "ix_taxioffers_driver_list"),
        ("TaxiRequestOffers", "ix_taxioffers_request"),
        ("TaxiRequestOffers", "ix_taxioffers_driver_selected"),
        ("TaxiBookings", "ux_taxibookings_request_active"),
        ("TaxiBookings", "ix_taxibookings_driver_active"),
        ("TaxiBookings", "ix_taxibookings_driver_dates"),
        ("TaxiBookings", "ix_taxibookings_traveller"),
        ("TaxiRatings", "ix_taxiratings_driver"),
        ("DueActions", "ux_dueactions_subject"),
        ("DueActions", "ix_dueactions_due"),
        ("DueActions", "ix_dueactions_lease"),
        ("DueActions", "ix_dueactions_request"),
        ("DueActions", "ix_dueactions_done"),
        ("TaxiRoutes", "ix_taxiroutes_to_from_city"),
        ("Trips", "ux_trips_invite_code"),
    ];

    private static readonly (string Table, string Column)[] NewColumns =
    [
        ("Trips", "NameChosen"),
        ("Trips", "InviteCode"),
        ("TaxiRoutes", "FromCityKey"),
        ("TaxiRoutes", "ToCityKey"),
    ];

    private static ApplicationDbContext NewContext() => new(new DbContextOptionsBuilder<ApplicationDbContext>()
        .UseNpgsql("Host=localhost;Database=design_only", o => o.UseNetTopologySuite())
        .Options);

    private static IModel SnapshotModel(ApplicationDbContext db)
    {
        var snapshot = db.GetService<IMigrationsAssembly>().ModelSnapshot
            ?? throw new Xunit.Sdk.XunitException("No model snapshot");
        var model = snapshot.Model;
        if (model is IMutableModel mutable) model = mutable.FinalizeModel();
        return db.GetService<IModelRuntimeInitializer>().Initialize(model, designTime: true, validationLogger: null);
    }

    private static Migration TheMigration(ApplicationDbContext db)
    {
        var assembly = db.GetService<IMigrationsAssembly>();
        var type = Assert.Single(assembly.Migrations).Value;
        return assembly.CreateMigration(type, db.Database.ProviderName!);
    }

    private static string MigrationsDir()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "RentNearBy.sln"))) dir = dir.Parent;
        Assert.NotNull(dir);
        return Path.Combine(dir!.FullName, "RentNearBy.Infrastructure", "Migrations");
    }

    [Fact]
    public void Exactly_one_migration_exists()
    {
        using var db = NewContext();
        var id = Assert.Single(db.GetService<IMigrationsAssembly>().Migrations).Key;
        Assert.EndsWith("_InitialCreate", id);

        var migrationTypes = typeof(ApplicationDbContext).Assembly.GetTypes()
            .Where(t => t.GetCustomAttribute<MigrationAttribute>() != null).ToList();
        Assert.Single(migrationTypes);
        Assert.Single(typeof(ApplicationDbContext).Assembly.GetTypes(), t => t.IsSubclassOf(typeof(ModelSnapshot)));

        var files = Directory.GetFiles(MigrationsDir(), "*.cs").Select(Path.GetFileName).OrderBy(f => f).ToArray();
        Assert.Equal(new[] { $"{id}.Designer.cs", $"{id}.cs", "ApplicationDbContextModelSnapshot.cs" }.OrderBy(f => f), files);
        Assert.StartsWith("// <auto-generated />", File.ReadAllText(Path.Combine(MigrationsDir(), $"{id}.Designer.cs")).TrimStart('﻿'));
        Assert.StartsWith("// <auto-generated />", File.ReadAllText(Path.Combine(MigrationsDir(), "ApplicationDbContextModelSnapshot.cs")).TrimStart('﻿'));
    }

    [Fact]
    public void Snapshot_has_every_new_table_and_index()
    {
        using var db = NewContext();
        var tables = SnapshotModel(db).GetRelationalModel().Tables.ToDictionary(t => t.Name);

        foreach (var name in NewTables)
            Assert.True(tables.ContainsKey(name), $"Snapshot has no table {name}");

        foreach (var (table, index) in NewIndexes)
            Assert.True(tables[table].Indexes.Any(i => i.Name == index), $"Snapshot has no index {index} on {table}");

        foreach (var (table, column) in NewColumns)
            Assert.NotNull(tables[table].FindColumn(column));

        Assert.True(tables["Trips"].Indexes.Single(i => i.Name == "ux_trips_invite_code").IsUnique);
        Assert.Equal("\"Status\" = 'Ringing'",
            tables["TaxiRequestOffers"].Indexes.Single(i => i.Name == "ux_taxioffers_driver_ringing").Filter);
    }

    [Fact]
    public void Model_has_no_changes_pending_against_the_snapshot()
    {
        using var db = NewContext();
        var current = db.GetService<IDesignTimeModel>().Model.GetRelationalModel();
        var snapshot = SnapshotModel(db).GetRelationalModel();

        var differences = db.GetService<IMigrationsModelDiffer>().GetDifferences(snapshot, current);

        Assert.True(differences.Count == 0,
            "Model changed since InitialCreate: " + string.Join(", ", differences.Select(d => d.GetType().Name)));
    }

    [Fact]
    public void Migration_contains_no_hand_written_sql_for_taxi_tables()
    {
        using var db = NewContext();
        var up = TheMigration(db).UpOperations;

        Assert.DoesNotContain(up, op => op is SqlOperation);

        var created = up.OfType<CreateTableOperation>().Select(o => o.Name).ToHashSet();
        foreach (var name in NewTables) Assert.Contains(name, created);

        var indexes = up.OfType<CreateIndexOperation>().Select(o => o.Name).ToHashSet();
        foreach (var (_, index) in NewIndexes) Assert.Contains(index, indexes);

        var id = Assert.Single(db.GetService<IMigrationsAssembly>().Migrations).Key;
        var source = File.ReadAllText(Path.Combine(MigrationsDir(), $"{id}.cs"));
        Assert.DoesNotContain("migrationBuilder.Sql(", source);
        Assert.DoesNotContain("btree_gist", source);
        Assert.DoesNotContain("EXCLUDE", source);
    }
}
